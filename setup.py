def mask_token(token: str) -> str:
    """Mask sensitive token for console display."""
    if len(token) > 12:
        return f"{token[:6]}...{token[-4:]}"
    return "***"


def mask_id(admin_id: str | int) -> str:
    """Mask admin ID middle digits for privacy."""
    s = str(admin_id)
    if len(s) > 4:
        return f"{s[:2]}***{s[-2:]}"
    return s


async def validate_telegram_token(token: str) -> tuple[bool, Any]:
    """Test token with getMe. Returns (is_valid, bot_info_or_error_msg)."""
    try:
        bot = Bot(token=token)
        info = await bot.get_me()
        return True, {"id": info.id, "username": info.username, "first_name": info.first_name}
    except Exception as e:
        return False, str(e)


def backup_env():
    """Create .env.bak if .env exists."""
    if os.path.exists(ENV_FILE):
        bak_file = f"{ENV_FILE}.bak"
        shutil.copy2(ENV_FILE, bak_file)
        print(f"📦 Backed up existing configuration to: {bak_file}")


def write_env_file(
    bot_token: str,
    admin_ids: str,
    access_mode: str,
    grizzly_key: str,
    service_code: str = "jio",
    max_price: str = "0.50",
):
    """Write sanitized environment variables to .env."""
    backup_env()
    content = (
        f"# ========================================================\n"
        f"# Jio Gemini 18-Month Hunter Configuration\n"
        f"# Auto-generated by setup.py on {time.strftime('%Y-%m-%d %H:%M:%S')}\n"
        f"# ========================================================\n\n"
        f"TELEGRAM_BOT_TOKEN={bot_token}\n"
        f"ADMIN_IDS={admin_ids}\n"
        f"ACCESS_MODE={access_mode}\n\n"
        f"GRIZZLY_API_KEY={grizzly_key}\n"
        f"DEFAULT_SERVICE_CODE={service_code}\n"
        f"DEFAULT_MAX_PRICE={max_price}\n"
        f"DEFAULT_COUNTRY_ID=22\n\n"
        f"# Proxy Configuration (Optional)\n"
        f"PROXY=\n"
    )
    with open(ENV_FILE, "w", encoding="utf-8") as f:
        f.write(content)

    # POSIX file permissions 0600
    try:
        os.chmod(ENV_FILE, 0o600)
    except Exception:
        pass

    print(f"✅ Configuration successfully saved to: {ENV_FILE}")


async def capture_admin_id_from_telegram(bot: Bot, timeout: int = 120) -> Optional[int]:
    """
    Poll getUpdates for 120 seconds to capture the first private message sender ID.
    Instructs the admin to message the bot.
    """
    print("\n" + "-" * 60)
    print("📡 INTERACTIVE ADMIN ID CAPTURE")
    print("-" * 60)
    print("1. Open Telegram on your phone or desktop.")
    print("2. Send ANY private message (e.g. 'hello' or '/start') to your bot.")
    print(f"⏳ Listening for incoming messages (timeout {timeout}s)...")

    start_time = time.time()
    last_update_id = 0

    while time.time() - start_time < timeout:
        try:
            updates = await bot.get_updates(offset=last_update_id + 1, timeout=3)
            for upd in updates:
                last_update_id = upd.update_id
                if upd.message and upd.message.chat.type == "private" and upd.message.from_user:
                    user_id = upd.message.from_user.id
                    name = upd.message.from_user.first_name or ""
                    username = upd.message.from_user.username or ""
                    user_tag = f"@{username}" if username else name
                    print(f"\n🎉 Captured Message from: {user_tag} (ID: {user_id})")
                    return user_id
        except TelegramError as e:
            if "conflict" in str(e).lower() or "webhook" in str(e).lower():
                print(f"⚠️ Notice: getUpdates capture not available: {e}")
                return None
        except Exception:
            pass
        await asyncio.sleep(1)

    print("⏰ Capture timed out. You can enter your numeric Telegram ID manually.")
    return None


async def run_setup(args):
    """Execute setup wizard according to CLI flags or interactive prompts."""
    print(BANNER)

    # 1. Bot Token
    token = args.token or os.getenv("TELEGRAM_BOT_TOKEN", "").strip()
    if token == "your_telegram_bot_token_here":
        token = ""

    bot_info = None
    bot = None

    if token:
        test_bot = Bot(token)
        try:
            bot_info = await test_bot.get_me()
            bot = test_bot
            print(f"✅ Verified Bot: {bot_info.first_name} (@{bot_info.username})")
            if args.force and not args.token and not args.non_interactive and not args.check and not args.dry_run:
                change_ans = input("Do you want to change this Bot Token? (y/N) [Default: N]: ").strip().lower()
                if change_ans in ("y", "yes"):
                    token = ""
                    bot = None
                    bot_info = None
        except Exception as e:
            print(f"❌ Configured TELEGRAM_BOT_TOKEN is invalid: {e}")
            if args.non_interactive:
                sys.exit(1)
            token = ""

    if not token and not args.non_interactive and not args.check and not args.dry_run:
        for attempt in range(1, 4):
            print("\n🔑 Telegram Bot Token Setup:")
            print("   Get your bot token from @BotFather on Telegram (e.g. 123456789:ABCdef...)")
            try:
                candidate = getpass.getpass("Enter Bot Token (hidden): ").strip()
            except Exception:
                candidate = input("Enter Bot Token: ").strip()

            if not candidate:
                continue

            test_bot = Bot(candidate)
            try:
                bot_info = await test_bot.get_me()
                token = candidate
                bot = test_bot
                print(f"✅ Verified Bot: {bot_info.first_name} (@{bot_info.username})")
                break
            except Exception as e:
                print(f"❌ Invalid token! Error: {e} (Attempt {attempt}/3)\n")

        if not token:
            print("❌ Setup aborted: Valid Telegram Bot Token is required.")
            sys.exit(1)

    # 2. Admin ID
    admin_ids_str = args.admin or os.getenv("ADMIN_IDS", "").strip()
    is_interactive = not args.non_interactive and not args.check and not args.dry_run

    if not admin_ids_str and is_interactive and bot:
        print("\n" + "-" * 60)
        print("👤 Admin Access Setup:")
        print("   How would you like to configure your Admin User ID?")
        print("   [1] Enter numeric ID manually")
        print("   [2] Send a message in Telegram to auto-capture your ID")
        choice = input("Select option (1 or 2) [Default: 2]: ").strip()

        if choice == "1":
            while True:
                val = input("Enter your numeric Telegram User ID (e.g. 123456789): ").strip()
                if val.isdigit():
                    admin_ids_str = val
                    break
                print("❌ ID must be a positive integer.")
        else:
            captured = await capture_admin_id_from_telegram(bot)
            if captured:
                admin_ids_str = str(captured)
            else:
                while True:
                    val = input("Enter your numeric Telegram User ID manually: ").strip()
                    if val.isdigit():
                        admin_ids_str = val
                        break
                    print("❌ ID must be a positive integer.")

    if not admin_ids_str:
        admin_ids_str = "0"

    # 3. Grizzly SMS API Key
    grizzly_key = args.grizzly_key or os.getenv("GRIZZLY_API_KEY", "").strip()
    if (not grizzly_key or grizzly_key == "your_grizzly_api_key_here") and is_interactive:
        print("\n" + "-" * 60)
        print("🌐 Grizzly SMS API Key Setup:")
        print("   Find your API key at: https://grizzlysms.com/profile/settings")
        key_input = input("Enter Grizzly SMS API Key (press Enter to skip): ").strip()
        if key_input:
            grizzly_key = key_input

    # Validate Grizzly Key if provided
    if grizzly_key and grizzly_key != "your_grizzly_api_key_here":
        is_valid, bal, msg = grizzly_client.test_and_save_api_key(grizzly_key)
        if is_valid:
            print(f"💰 Verified Grizzly SMS Wallet Balance: ${bal:.2f} USD")
        else:
            print(f"⚠️ Notice: Grizzly API validation returned: {msg}")

    # 4. Access Mode
    access_mode = os.getenv("ACCESS_MODE", "admin_only").strip()

    if args.check:
        print("\n🔍 --check mode: All checks passed. Exiting without modifying files.")
        return

    if args.dry_run:
        print("\n🔍 --dry-run mode: Configuration validated. No files written.")
        print(f"• Bot: @{bot_info.username if bot_info else 'Unknown'}")
        print(f"• Admin IDs: {admin_ids_str}")
        print(f"• Access Mode: {access_mode}")
        return

    # 5. Write to .env
    write_env_file(
        bot_token=token,
        admin_ids=admin_ids_str,
        access_mode=access_mode,
        grizzly_key=grizzly_key or "your_grizzly_api_key_here",
    )

    # 6. Apply Bot Profile & Scoped Commands
    if bot:
        print("\n" + "-" * 60)
        print("🎨 Deploying Brand Profile & Scoped Command Menu...")
        print("-" * 60)
        profile_res = await profile_manager.apply_profile(bot, force=args.force)
        for k, v in profile_res.items():
            print(f"• {k.capitalize()}: {v}")

        # Register scoped commands
        admin_id_list = [int(i) for i in admin_ids_str.split(",") if i.isdigit()]
        await profile_manager.register_scoped_commands(bot, admin_id_list)
        print("• Scoped Commands: Registered (Public scope + Admin scope)")

    # 7. Final Summary
    print("\n" + "=" * 60)
    print("🎉 SETUP COMPLETE & SECURED!")
    print("=" * 60)
    print(f"• Bot Identity : @{bot_info.username if bot_info else 'Configured'}")
    print(f"• Admin ID(s)  : {', '.join([mask_id(i) for i in admin_ids_str.split(',')])}")
    print(f"• Access Mode  : {access_mode} (Admin-locked)")
    print(f"• Storage      : Saved permanently to .env (0600)")
    print("\n👉 Launch your bot using:")
    print("   • Windows : start_bot.bat")
    print("   • Linux   : ./start_bot.sh")
    print("   • Manual  : python bot.py")
    print("=" * 60 + "\n")


def main():
    parser = argparse.ArgumentParser(description="One-Command Terminal Setup for Jio Gemini Hunter Bot")
    parser.add_argument("--token", type=str, help="Telegram Bot Token from @BotFather")
    parser.add_argument("--admin", type=str, help="Numeric Admin Telegram User ID")
    parser.add_argument("--grizzly-key", type=str, help="Grizzly SMS API Key")
    parser.add_argument("--non-interactive", action="store_true", help="Non-interactive setup using flags/env only")
    parser.add_argument("--check", action="store_true", help="Validate credentials and exit without changing files")
    parser.add_argument("--dry-run", action="store_true", help="Print actions without writing changes")
    parser.add_argument("--force", action="store_true", help="Force re-send all profile fields regardless of hash")
    args = parser.parse_args()

    asyncio.run(run_setup(args))


if __name__ == "__main__":
    main()
